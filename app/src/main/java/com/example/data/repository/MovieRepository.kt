  fun search(
    query: String,
    type: MediaType = MediaType.ALL,
    category: ContentCategory = ContentCategory.ALL,
    genre: String? = null,
    quality: String? = null,
    languageFilter: String? = null,
    minRating: Double = 0.0,
    sortBy: String = "Popular"
  ): List<MediaItem> {
    val qClean = query.trim().replace(Regex("[^a-zA-Z0-9 ]"), " ").lowercase()
    val qTokens = qClean.split(" ").filter { it.isNotBlank() }

    var filtered = allItems.filter { item ->
      val matchesQuery = if (qTokens.isEmpty()) {
        true
      } else {
        val titleClean = item.title.replace(Regex("[^a-zA-Z0-9 ]"), " ").lowercase()
        val aliasClean = item.aliases.joinToString(" ").lowercase()
        val genresClean = item.genres.joinToString(" ").lowercase()
        val castClean = item.cast.joinToString(" ").lowercase()
        val dirClean = item.director.lowercase()
        val langClean = item.audioLanguage.lowercase()
        val storylineClean = item.storyline.lowercase()
        val catClean = item.category.label.lowercase()

        val fullSearchable = "$titleClean $aliasClean $genresClean $castClean $dirClean $langClean $storylineClean $catClean"

        qTokens.all { token ->
          fullSearchable.contains(token) ||
          item.aliases.any { it.contains(token, ignoreCase = true) }
        }
      }

      val matchesType = (type == MediaType.ALL) || (item.type == type)

      val matchesCategory = (category == ContentCategory.ALL) ||
        (if (category == ContentCategory.UHD_4K) item.qualityBadge.contains("4K") else item.category == category)

      val matchesGenre = genre.isNullOrBlank() || genre == "All" ||
        item.genres.any { it.equals(genre, ignoreCase = true) }

      val matchesQuality = quality.isNullOrBlank() || quality == "All" ||
        item.qualityBadge.contains(quality, ignoreCase = true)

      val matchesLang = languageFilter.isNullOrBlank() || languageFilter == "All" ||
        item.audioLanguage.contains(languageFilter, ignoreCase = true)

      val matchesRating = item.rating >= minRating

      matchesQuery && matchesType && matchesCategory && matchesGenre && matchesQuality && matchesLang && matchesRating
    }

    filtered = when (sortBy) {
      "Top Rated" -> filtered.sortedByDescending { it.rating }
      "Newest" -> filtered.sortedByDescending { it.year }
      "A-Z" -> filtered.sortedBy { it.title }
      else -> filtered.sortedByDescending {
        if (it.isTop10 && it.top10Rank != null) 100 - it.top10Rank else if (it.isTrending) 10 else 0
      }
    }

    return filtered
  }

